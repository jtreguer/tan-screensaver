#!/usr/bin/env node
// Dumps reference trajectories, palette LUTs and mulberry32 output from flow.js as TOML
// fixtures for the Rust tests. flow.js is patched in memory to expose what render() does
// internally; every patch must match exactly once, so a change in flow.js fails loudly
// instead of producing fixtures from a different algorithm.
//
// Usage: node tools/dump-fixtures.js [path/to/flow.js]

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const flowPath = process.argv[2] || path.join(os.homedir(), "Work/web_dev/tan-trajectories/flow.js");
const outDir = path.join(__dirname, "..", "tests", "fixtures");

let src = fs.readFileSync(flowPath, "utf8");
function patch(from, to) {
  const n = src.split(from).length - 1;
  if (n !== 1) throw new Error(`expected one match in flow.js for ${JSON.stringify(from)}, found ${n}`);
  src = src.replace(from, to);
}
patch("const trace = (sx, sy, dir) => {",
  "const trace = (sx, sy, dir) => {\n      if (opts.onTrace) opts.onTrace(sx, sy, dir);");
patch("const t = signed ?",
  "if (opts.onStep) opts.onStep(x, y, kappa);\n        const t = signed ?");
patch("splat((x - x0w) * ppu, (y0w - y) * ppu, Math.min(255, Math.max(0, Math.round(t * 255))) * 3);",
  "const ci = Math.min(255, Math.max(0, Math.round(t * 255)));\n" +
  "        if (opts.onColour) opts.onColour(ci);\n" +
  "        splat((x - x0w) * ppu, (y0w - y) * ppu, ci * 3);");
patch("return { SYSTEMS, PALETTES, render };",
  "return { SYSTEMS, PALETTES, render, paletteLut, mulberry32 };");
const M = new Function(src + "\nreturn flowModule;")()();

function provenance() {
  const dir = path.dirname(flowPath);
  try {
    const head = execFileSync("git", ["-C", dir, "rev-parse", "--short", "HEAD"]).toString().trim();
    const dirty = execFileSync("git", ["-C", dir, "status", "--porcelain", "flow.js"]).toString().trim();
    return `${head}${dirty ? " (flow.js modified)" : ""}`;
  } catch {
    return "unknown";
  }
}

// TOML needs a dot or exponent to read a value as a float.
function num(v) {
  if (!Number.isFinite(v)) throw new Error(`non-finite value ${v}`);
  return Number.isInteger(v) ? v.toFixed(1) : String(v);
}
const arr = (a, f = num) => `[${Array.from(a, f).join(", ")}]`;
const str = (s) => JSON.stringify(s);

const CASES = [
  { name: "whirlpools original", system: "whirlpools", preset: "Whirlpools (original)",
    W: 160, H: 90, step: 0.5, arc: 30, seeds: 3, seed: 7, both: true, colorMode: "magnitude", kappa0: 1.5 },
  { name: "spirals original, signed", system: "spirals", preset: "Spiral garden (original)",
    W: 160, H: 90, step: 1, arc: 30, seeds: 3, seed: 11, both: true, colorMode: "signed", kappa0: 1.5 },
  { name: "whirlpools high frequency, long arc", system: "whirlpools", preset: "High frequency",
    W: 160, H: 90, step: 2, arc: 60, seeds: 4, seed: 42, both: true, colorMode: "magnitude", kappa0: 0.8 },
  { name: "spirals close-up, portrait", system: "spirals", preset: "Close-up",
    W: 90, H: 160, step: 0.5, arc: 10, seeds: 3, seed: 3, both: true, colorMode: "signed", kappa0: 3 },
  { name: "whirlpools wide field, forward only", system: "whirlpools", preset: "Wide field",
    W: 160, H: 90, step: 1, arc: 30, seeds: 3, seed: 5, both: false, colorMode: "magnitude", kappa0: 1.5 },
];

function dumpTrajectories() {
  const lines = [
    `# Generated by tools/dump-fixtures.js from flow.js at ${provenance()}. Do not edit.`,
    "",
  ];
  for (const c of CASES) {
    const sys = M.SYSTEMS[c.system];
    const p = sys.presets[c.preset];
    const params = Object.fromEntries(Object.keys(sys.params).map((k) => [k, p[k]]));
    const traces = [];
    let cur = null;
    M.render(c.W, c.H, {
      system: c.system, params, cx: p.cx, cy: p.cy, span: p.span,
      seeds: c.seeds, seed: c.seed, arc: c.arc, step: c.step, both: c.both,
      width: 1, exposure: 0.35, kappa0: c.kappa0, colorMode: c.colorMode,
      palette: "Magma", reverse: false, bg: "#0b0c10",
      onTrace: (sx, sy, dir) => traces.push((cur = { sx, sy, dir, x: [], y: [], kappa: [], ci: [] })),
      onStep: (x, y, kappa) => { cur.x.push(x); cur.y.push(y); cur.kappa.push(kappa); },
      onColour: (ci) => cur.ci.push(ci),
    });
    lines.push(
      "[[case]]",
      `name = ${str(c.name)}`,
      `system = ${str(c.system)}`,
      `params = ${arr(Object.values(params))}`,
      `cx = ${num(p.cx)}`, `cy = ${num(p.cy)}`, `span = ${num(p.span)}`,
      `width_px = ${c.W}`, `height_px = ${c.H}`,
      `step_px = ${num(c.step)}`, `arc = ${num(c.arc)}`,
      `seeds = ${c.seeds}`, `seed = ${c.seed}`, `both = ${c.both}`,
      `colour_mode = ${str(c.colorMode)}`, `kappa0 = ${num(c.kappa0)}`,
      "",
    );
    for (const t of traces) {
      lines.push(
        "[[case.trace]]",
        `sx = ${num(t.sx)}`, `sy = ${num(t.sy)}`, `dir = ${num(t.dir)}`,
        `x = ${arr(t.x)}`, `y = ${arr(t.y)}`, `kappa = ${arr(t.kappa)}`, `ci = ${arr(t.ci, String)}`,
        "",
      );
    }
  }
  fs.writeFileSync(path.join(outDir, "trajectories.toml"), lines.join("\n"));
}

function dumpPalettesAndRng() {
  const lines = [
    `# Generated by tools/dump-fixtures.js from flow.js at ${provenance()}. Do not edit.`,
    "",
  ];
  for (const seed of [0, 7, 42, 123456789, 4294967295]) {
    const rng = M.mulberry32(seed);
    lines.push("[[rng]]", `seed = ${seed}`, `values = ${arr(Array.from({ length: 16 }, rng))}`, "");
  }
  // A sample of LUT entries is enough to pin the interpolation; 255 checks the last stop.
  const index = [];
  for (let i = 0; i < 256; i += 5) index.push(i);
  index.push(254, 255);
  for (const [name, stops] of Object.entries(M.PALETTES)) {
    for (const reverse of [false, true]) {
      const lut = M.paletteLut(stops, reverse);
      const rgb = index.flatMap((i) => [lut[i * 3], lut[i * 3 + 1], lut[i * 3 + 2]]);
      lines.push("[[palette]]", `name = ${str(name)}`, `reverse = ${reverse}`,
        `index = ${arr(index, String)}`, `rgb = ${arr(rgb)}`, "");
    }
  }
  fs.writeFileSync(path.join(outDir, "palettes_rng.toml"), lines.join("\n"));
}

fs.mkdirSync(outDir, { recursive: true });
dumpTrajectories();
dumpPalettesAndRng();
console.log(`fixtures written to ${outDir}`);
