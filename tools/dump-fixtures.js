function dumpTrajectories() {
  const lines = [
    `# Generated by tools/dump-fixtures.js from flow.js at ${provenance()}. Do not edit.`,
    "",
  ];
  for (const c of CASES) {
    const sys = M.SYSTEMS[c.system];
    const p = sys.presets[c.preset];
    const params = Object.fromEntries(Object.keys(sys.params).map((k) => [k, p[k]]));
    const traces = [];
    let cur = null;
    M.render(c.W, c.H, {
      system: c.system, params, cx: p.cx, cy: p.cy, span: p.span,
      seeds: c.seeds, seed: c.seed, arc: c.arc, step: c.step, both: c.both,
      width: 1, exposure: 0.35, kappa0: c.kappa0, colorMode: c.colorMode,
      palette: "Magma", reverse: false, bg: "#0b0c10",
      onTrace: (sx, sy, dir) => traces.push((cur = { sx, sy, dir, x: [], y: [], kappa: [], ci: [] })),
      onStep: (x, y, kappa) => { cur.x.push(x); cur.y.push(y); cur.kappa.push(kappa); },
      onColour: (ci) => cur.ci.push(ci),
    });
    lines.push(
      "[[case]]",
      `name = ${str(c.name)}`,
      `system = ${str(c.system)}`,
      `params = ${arr(Object.values(params))}`,
      `cx = ${num(p.cx)}`, `cy = ${num(p.cy)}`, `span = ${num(p.span)}`,
      `width_px = ${c.W}`, `height_px = ${c.H}`,
      `step_px = ${num(c.step)}`, `arc = ${num(c.arc)}`,
      `seeds = ${c.seeds}`, `seed = ${c.seed}`, `both = ${c.both}`,
      `colour_mode = ${str(c.colorMode)}`, `kappa0 = ${num(c.kappa0)}`,
      "",
    );
    for (const t of traces) {
      lines.push(
        "[[case.trace]]",
        `sx = ${num(t.sx)}`, `sy = ${num(t.sy)}`, `dir = ${num(t.dir)}`,
        `x = ${arr(t.x)}`, `y = ${arr(t.y)}`, `kappa = ${arr(t.kappa)}`, `ci = ${arr(t.ci, String)}`,
        "",
      );
    }
  }
  fs.writeFileSync(path.join(outDir, "trajectories.toml"), lines.join("\n"));
}

function dumpPalettesAndRng() {
  const lines = [
    `# Generated by tools/dump-fixtures.js from flow.js at ${provenance()}. Do not edit.`,
    "",
  ];
  for (const seed of [0, 7, 42, 123456789, 4294967295]) {
    const rng = M.mulberry32(seed);
    lines.push("[[rng]]", `seed = ${seed}`, `values = ${arr(Array.from({ length: 16 }, rng))}`, "");
  }
  // A sample of LUT entries is enough to pin the interpolation; 255 checks the last stop.
  const index = [];
  for (let i = 0; i < 256; i += 5) index.push(i);
  index.push(254, 255);
  for (const [name, stops] of Object.entries(M.PALETTES)) {
    for (const reverse of [false, true]) {
      const lut = M.paletteLut(stops, reverse);
      const rgb = index.flatMap((i) => [lut[i * 3], lut[i * 3 + 1], lut[i * 3 + 2]]);
      lines.push("[[palette]]", `name = ${str(name)}`, `reverse = ${reverse}`,
        `index = ${arr(index, String)}`, `rgb = ${arr(rgb)}`, "");
    }
  }
  fs.writeFileSync(path.join(outDir, "palettes_rng.toml"), lines.join("\n"));
}

// Minimal RGB PNG encoder; Node has zlib but no image codec.
function encodePng(W, H, rgba) {
  const raw = Buffer.alloc((W * 3 + 1) * H);
  for (let y = 0; y < H; y++) {
    const row = y * (W * 3 + 1);
    for (let x = 0; x < W; x++) {
      for (let c = 0; c < 3; c++) raw[row + 1 + x * 3 + c] = rgba[(y * W + x) * 4 + c];
    }
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(zlib.crc32(body));
    return Buffer.concat([len, body, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0);
  ihdr.writeUInt32BE(H, 4);
  ihdr[8] = 8; ihdr[9] = 2; // 8-bit RGB
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr), chunk("IDAT", zlib.deflateSync(raw)), chunk("IEND", Buffer.alloc(0)),
  ]);
}

