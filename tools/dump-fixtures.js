function dumpImages() {
  fs.mkdirSync(path.join(outDir, "images"), { recursive: true });
  const lines = [
    `# Generated by tools/dump-fixtures.js from flow.js at ${provenance()}. Do not edit.`,
    "# Each case is rendered by flow.js's render() into images/<name>.png.",
    "",
  ];
  for (const c of IMAGES) {
    const sys = M.SYSTEMS[c.system];
    const p = sys.presets[c.preset];
    const params = Object.fromEntries(Object.keys(sys.params).map((k) => [k, p[k]]));
    const rgba = M.render(c.W, c.H, {
      system: c.system, params, cx: p.cx, cy: p.cy, span: p.span,
      seeds: c.seeds, seed: c.seed, arc: c.arc, step: c.step, both: c.both,
      width: c.width, exposure: c.exposure, kappa0: c.kappa0, colorMode: c.colorMode,
      palette: c.palette, reverse: c.reverse, bg: c.bg,
    });
    fs.writeFileSync(path.join(outDir, "images", `${c.name}.png`), encodePng(c.W, c.H, rgba));
    lines.push(
      "[[image]]",
      `name = ${str(c.name)}`,
      `system = ${str(c.system)}`,
      `params = ${arr(Object.values(params))}`,
      `cx = ${num(p.cx)}`, `cy = ${num(p.cy)}`, `span = ${num(p.span)}`,
      `width_px = ${c.W}`, `height_px = ${c.H}`,
      `seeds = ${c.seeds}`, `seed = ${c.seed}`, `arc = ${num(c.arc)}`, `step_px = ${num(c.step)}`,
      `both = ${c.both}`, `line_width_px = ${num(c.width)}`, `exposure = ${num(c.exposure)}`,
      `kappa0 = ${num(c.kappa0)}`, `colour_mode = ${str(c.colorMode)}`,
      `palette = ${str(c.palette)}`, `reverse = ${c.reverse}`, `background = ${str(c.bg)}`,
      "",
    );
  }
  fs.writeFileSync(path.join(outDir, "images.toml"), lines.join("\n"));
}

