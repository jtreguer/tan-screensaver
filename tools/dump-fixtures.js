#!/usr/bin/env node
// Dumps reference trajectories, palette LUTs, mulberry32 output and rendered images from
// flow.js as fixtures for the Rust tests. flow.js is patched in memory to expose what render() does
// internally; every patch must match exactly once, so a change in flow.js fails loudly
// instead of producing fixtures from a different algorithm.
//
// Usage: node tools/dump-fixtures.js [path/to/flow.js]

const fs = require("fs");
const os = require("os");
const path = require("path");
const zlib = require("zlib");
const { execFileSync } = require("child_process");

const flowPath = process.argv[2] || path.join(os.homedir(), "Work/web_dev/tan-trajectories/flow.js");
const outDir = path.join(__dirname, "..", "tests", "fixtures");

let src = fs.readFileSync(flowPath, "utf8");
function patch(from, to) {
  const n = src.split(from).length - 1;
  if (n !== 1) throw new Error(`expected one match in flow.js for ${JSON.stringify(from)}, found ${n}`);
  src = src.replace(from, to);
}
patch("const trace = (sx, sy, dir) => {",
  "const trace = (sx, sy, dir) => {\n      if (opts.onTrace) opts.onTrace(sx, sy, dir);");
patch("const t = signed ?",
  "if (opts.onStep) opts.onStep(x, y, kappa);\n        const t = signed ?");
patch("splat((x - x0w) * ppu, (y0w - y) * ppu, Math.min(255, Math.max(0, Math.round(t * 255))) * 3);",
  "const ci = Math.min(255, Math.max(0, Math.round(t * 255)));\n" +
  "        if (opts.onColour) opts.onColour(ci);\n" +
  "        splat((x - x0w) * ppu, (y0w - y) * ppu, ci * 3);");
patch("return { SYSTEMS, PALETTES, render };",
  "return { SYSTEMS, PALETTES, render, paletteLut, mulberry32 };");
const M = new Function(src + "\nreturn flowModule;")()();

function provenance() {
  const dir = path.dirname(flowPath);
  try {
    const head = execFileSync("git", ["-C", dir, "rev-parse", "--short", "HEAD"]).toString().trim();
    const dirty = execFileSync("git", ["-C", dir, "status", "--porcelain", "flow.js"]).toString().trim();
    return `${head}${dirty ? " (flow.js modified)" : ""}`;
  } catch {
    return "unknown";
  }
}

// TOML needs a dot or exponent to read a value as a float.
function num(v) {
  if (!Number.isFinite(v)) throw new Error(`non-finite value ${v}`);
  return Number.isInteger(v) ? v.toFixed(1) : String(v);
}
const arr = (a, f = num) => `[${Array.from(a, f).join(", ")}]`;
const str = (s) => JSON.stringify(s);

